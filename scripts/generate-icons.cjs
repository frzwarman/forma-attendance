// Generates src/components/icons.tsx: inline SVG icons from lucide's data, so the
// admin pages do not pull the whole icon set and react-native-svg into the bundle.
const fs = require('node:fs');
const path = require('node:path');

const icons = {
  LayoutList: 'layout-list', Gift: 'gift', Palette: 'palette', LogOut: 'log-out', Users: 'users',
  CalendarCheck: 'calendar-check', Paperclip: 'paperclip', Trophy: 'trophy', Search: 'search',
  FileSpreadsheet: 'file-spreadsheet', FileText: 'file-text', Save: 'save', RotateCcw: 'rotate-ccw',
  Calendar: 'calendar', Camera: 'camera', SwitchCamera: 'switch-camera', X: 'x', Upload: 'upload',
  ChevronLeft: 'chevron-left', ChevronRight: 'chevron-right', MessageCircle: 'message-circle', CircleCheck: 'circle-check',
  Presentation: 'presentation', Download: 'download', Plus: 'plus',
};
const dir = path.resolve('node_modules/lucide-react-native/dist/esm/icons');
let out = `// Generated by scripts/generate-icons.cjs from lucide (ISC). Do not edit by hand.
import React from "react";

export type IconComponent = (props: { size?: number; color?: string; strokeWidth?: number }) => React.JSX.Element;
type Node = [string, Record<string, string>];

function make(nodes: Node[]): IconComponent {
  return function Icon({ size = 24, color = "currentColor", strokeWidth = 2 }) {
    return (
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke={color} strokeWidth={strokeWidth} strokeLinecap="round" strokeLinejoin="round" aria-hidden>
        {nodes.map(([tag, attrs], index) => React.createElement(tag, { key: index, ...attrs }))}
      </svg>
    );
  };
}
`;
for (const [name, file] of Object.entries(icons)) {
  const source = fs.readFileSync(path.join(dir, `${file}.js`), 'utf8');
  const match = /createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\);/.exec(source);
  if (!match) throw new Error(`No icon data in ${file}`);
  const nodes = new Function(`return ${match[1]}`)().map(([tag, attrs]) => {
    const { key, ...rest } = attrs;
    return [tag, rest];
  });
  out += `\nexport const ${name} = make(${JSON.stringify(nodes)});\n`;
}
fs.writeFileSync(path.resolve('src/components/icons.tsx'), out);
console.log(`icons.tsx: ${Object.keys(icons).length} icons`);
